"""
Verification tools: runs tests, linters, builds, and registers verifiable outcomes.
Captures trusted execution evidence directly from the test-runner process via structured output.

Cryptographic Provenance Guarantees & Limitations:
- Guarantees: The HMAC-SHA256 signature on TrustedExecutionRecord proves that the host runtime
  directly observed, parsed, and authenticated the runner's stdout summary, individual testcase
  execution lines, and bounded JUnit XML reports. It guarantees that the evidence record was
  issued by this runtime, bound to the specific task_id, and has not been altered after execution.
- Limitations: HMAC signatures on execution records prove observation integrity, but cannot
  cryptographically attest to the internal semantic validity of untrusted test code in the
  workspace (e.g. tests that contain trivial assert True, monkeypatches, or stubbed assertions).
  AST validation and container isolation constrain malicious hooks, but rigorous verification
  relies on pre-existing or human-reviewed test specifications.
"""
import ast
import os
import shutil
import tempfile
import time
import uuid
import xml.etree.ElementTree as ET
from typing import Any, Dict, List, Optional, Set
from agent.tools.base import BaseTool
from agent.tools.terminal import RunCommandTool, register_authorized_evidence_dir, unregister_authorized_evidence_dir
from agent.core.models import PermissionLevel, ActionResult, VerificationCheckType
from agent.security.provenance import issue_trusted_execution_record, TrustedExecutionRecord

MAX_JUNIT_XML_BYTES = 5 * 1024 * 1024  # 5MB strict limit on report size
MAX_TESTCASES = 2000  # Cap testcase count to prevent memory exhaustion / DoS


def extract_pytest_console_summary(output: str) -> Optional[Dict[str, int]]:
    """
    Extracts pytest's authenticated terminal summary line directly from the runner's stdout.
    Examples:
    '=== 10 passed in 0.12s ==='
    '=== 2 failed, 8 passed, 1 skipped in 0.45s ==='
    '=== 1 failed, 1 error, 5 passed in 0.30s ==='
    """
    if not output:
        return None

    import re
    pattern = re.compile(r"={2,}\s+(.*?)\s+in\s+[\d\.]+[a-zA-Z]*\s+={2,}", re.IGNORECASE)
    matches = pattern.findall(output)
    if not matches:
        alt_pattern = re.compile(
            r"={2,}\s+([0-9\s,a-zA-Z]+(?:passed|failed|skipped|error|warning)[0-9\s,a-zA-Z]*)\s+={2,}",
            re.IGNORECASE,
        )
        matches = alt_pattern.findall(output)
        if not matches:
            return None

    summary_text = matches[-1]
    passed = 0
    failed = 0
    skipped = 0

    passed_m = re.search(r"(\d+)\s+passed", summary_text)
    if passed_m:
        passed = int(passed_m.group(1))

    failed_m = re.search(r"(\d+)\s+failed", summary_text)
    if failed_m:
        failed = int(failed_m.group(1))

    error_m = re.search(r"(\d+)\s+error", summary_text)
    if error_m:
        failed += int(error_m.group(1))

    skipped_m = re.search(r"(\d+)\s+skipped", summary_text)
    if skipped_m:
        skipped = int(skipped_m.group(1))

    total = passed + failed + skipped
    if total == 0:
        return None

    return {
        "total": total,
        "passed": passed,
        "failed": failed,
        "skipped": skipped,
    }


def extract_pytest_console_passed_nodes(output: str) -> Set[str]:
    """
    Extracts individual test node names printed as PASSED directly in the runner's stdout stream.
    Matches lines like:
    'tests/test_auth.py::test_login PASSED [ 50%]'
    'tests/test_math.py::TestCalc::test_add PASSED [100%]'
    Stores exact canonical node identifiers (e.g. 'tests/test_auth.py::test_login').
    Rejects standalone function names or loose basenames.
    """
    if not output:
        return set()

    passed_nodes = set()
    for line in output.splitlines():
        line_clean = line.strip()
        if " PASSED" in line_clean:
            raw_target = line_clean.split(" PASSED")[0].strip()
            if raw_target:
                clean_target = os.path.normpath(raw_target).replace("\\", "/").lower()
                passed_nodes.add(clean_target)
                if "::" in clean_target:
                    parts = clean_target.split("::")
                    # For class-based tests: tests/test_calc.py::TestClass::test_add
                    # also allow exact file::test_name mapping
                    if len(parts) > 2:
                        passed_nodes.add(f"{parts[0]}::{parts[-1]}")

    return passed_nodes


def parse_junit_xml_report(xml_path: str) -> Optional[Dict[str, Any]]:
    """
    Parses a JUnit XML report file directly generated by a test runner (e.g. pytest --junitxml).
    Counts test cases directly (not identifiers), tracks passed, failed, and skipped separately,
    validates count consistency (total == passed + failed + skipped),
    strictly caps file size and testcase counts to prevent DoS, rejects duplicate entries,
    and explicitly rejects empty or zero-pass reports.
    """
    if not os.path.exists(xml_path) or os.path.islink(xml_path):
        return None

    try:
        fsize = os.path.getsize(xml_path)
        if fsize == 0 or fsize > MAX_JUNIT_XML_BYTES:
            return None

        tree = ET.parse(xml_path)
        root = tree.getroot()
        passed_nodes: List[str] = []
        failed_nodes: List[str] = []
        skipped_nodes: List[str] = []
        passed_testcases: List[Dict[str, str]] = []

        # JUnit XML can have <testcase> under root or inside <testsuite>
        testcases = root.findall(".//testcase")
        total_testcases = len(testcases)
        if total_testcases == 0 or total_testcases > MAX_TESTCASES:
            return None

        passed_testcase_count = 0
        failed_testcase_count = 0
        skipped_testcase_count = 0
        seen_cases: Set[tuple] = set()

        for tc in testcases:
            name = tc.get("name", "")
            classname = tc.get("classname", "")
            file_attr = tc.get("file", "")

            # If classname is given and file not given
            if not file_attr and classname:
                parts = classname.split(".")
                file_attr = "/".join(parts) + ".py"

            case_key = (file_attr.replace("\\", "/").lower() if file_attr else "", classname.lower(), name.lower())
            if case_key in seen_cases:
                # Duplicate testcase entry indicates report tampering, replay, or corrupted file
                return None
            seen_cases.add(case_key)

            has_failure = tc.find("failure") is not None
            has_error = tc.find("error") is not None
            has_skipped = tc.find("skipped") is not None

            # Build identifiable node targets
            nodes = []
            if name:
                nodes.append(name.lower())
            if file_attr and name:
                clean_file = file_attr.replace("\\", "/").lower()
                nodes.append(f"{clean_file}::{name.lower()}")
                nodes.append(clean_file)
                base = os.path.basename(clean_file)
                nodes.append(base)
                nodes.append(os.path.splitext(base)[0])
            elif classname and name:
                nodes.append(f"{classname.lower()}::{name.lower()}")

            if has_failure or has_error:
                failed_testcase_count += 1
                failed_nodes.extend(nodes)
            elif has_skipped:
                skipped_testcase_count += 1
                skipped_nodes.extend(nodes)
            else:
                passed_testcase_count += 1
                passed_nodes.extend(nodes)
                passed_testcases.append({
                    "name": name.lower(),
                    "file": file_attr.replace("\\", "/").lower() if file_attr else "",
                    "classname": classname.lower() if classname else "",
                })

        # Validate count consistency: total must match sum of individual testcase outcomes
        if total_testcases != (passed_testcase_count + failed_testcase_count + skipped_testcase_count):
            return None
        if passed_testcase_count == 0:
            return None

        return {
            "total": total_testcases,
            "passed": passed_testcase_count,
            "failed": failed_testcase_count,
            "skipped": skipped_testcase_count,
            "passed_nodes": list(set(passed_nodes)),
            "passed_testcases": passed_testcases,
            "failed_nodes": list(set(failed_nodes)),
            "skipped_nodes": list(set(skipped_nodes)),
        }
    except Exception:
        return None


class RunVerificationCheckTool(BaseTool):
    name = "run_verification"
    description = (
        "Execute formal verification. Cryptographically verified structured execution records "
        "(with dual-channel validation and host AST verification) are supported for pytest. "
        "Other verification checks (build, lint, typecheck, or custom commands) are verified "
        "via exit status and execution summaries."
    )
    permission_level = PermissionLevel.SENSITIVE_OPERATION

    def __init__(self):
        self._command_tool = RunCommandTool()

    def get_parameters_schema(self) -> Dict[str, Any]:
        return {
            "type": "object",
            "properties": {
                "check_name": {
                    "type": "string",
                    "description": "Descriptive name for the verification check (e.g. 'Unit Tests', 'TypeScript Compile').",
                },
                "check_type": {
                    "type": "string",
                    "enum": [e.value for e in VerificationCheckType],
                    "description": "Category: 'test', 'build', 'lint', 'typecheck', 'git_diff', or 'custom'.",
                    "default": "test",
                },
                "command": {
                    "type": "string",
                    "description": "Shell command line to execute.",
                },
            },
            "required": ["check_name", "command"],
        }

    async def execute(self, workspace_path: str, **kwargs) -> ActionResult:
        t0 = time.time()
        call_id = kwargs.get("call_id", "run_verification")
        check_name = kwargs.get("check_name", "Verification Check")
        check_type = kwargs.get("check_type", "test")
        command = (kwargs.get("command") or "").strip()

        # Strict syntactic check to prevent shell chaining and evidence tampering
        forbidden_patterns = [
            (";", "semicolon command separator"),
            ("&&", "logical AND chaining"),
            ("||", "logical OR chaining"),
            ("|", "pipe operator"),
            ("&", "backgrounding operator"),
            ("\n", "newline command separator"),
            ("\r", "newline command separator"),
            (">", "output redirection"),
            ("<", "input redirection"),
            ("$", "subshell or variable substitution"),
            ("`", "backtick subshell substitution"),
        ]
        for op, desc in forbidden_patterns:
            if op in command:
                return ActionResult(
                    call_id=call_id,
                    tool_name=self.name,
                    success=False,
                    output="",
                    error=(
                        f"Verification command syntax error: Detected {desc} ('{op}'). "
                        "Shell chaining, redirection, backgrounding, subshells, and variable substitutions "
                        "are strictly prohibited in verification commands to prevent evidence tampering."
                    ),
                    artifacts={"command": command, "tampering_detected": True},
                    execution_time_ms=(time.time() - t0) * 1000,
                )

        # Prohibit user-supplied report overrides, custom plugin injections, or help flags
        cmd_lower = command.lower()
        if "--junitxml" in cmd_lower or "-o junit" in cmd_lower:
            return ActionResult(
                call_id=call_id,
                tool_name=self.name,
                success=False,
                output="",
                error="Verification command syntax error: Manual '--junitxml' flag is prohibited. The verification system attaches authenticated report destinations automatically.",
                artifacts={"command": command, "tampering_detected": True},
                execution_time_ms=(time.time() - t0) * 1000,
            )
        # Block arbitrary external pytest plugin injection that could hook or tamper with report generation
        if "-p " in cmd_lower:
            # Only allow disabling plugins with -p no:...
            parts = command.split()
            for i, p in enumerate(parts):
                if p == "-p" and i + 1 < len(parts):
                    val = parts[i + 1]
                    if not val.startswith("no:"):
                        return ActionResult(
                            call_id=call_id,
                            tool_name=self.name,
                            success=False,
                            output="",
                            error=f"Verification command syntax error: External pytest plugin injection ('-p {val}') is prohibited to prevent evidence tampering.",
                            artifacts={"command": command, "tampering_detected": True},
                            execution_time_ms=(time.time() - t0) * 1000,
                        )
        if "--help" in cmd_lower or " -h" in cmd_lower:
            return ActionResult(
                call_id=call_id,
                tool_name=self.name,
                success=False,
                output="",
                error="Verification command syntax error: Help flags are prohibited in formal verification execution.",
                artifacts={"command": command, "tampering_detected": True},
                execution_time_ms=(time.time() - t0) * 1000,
            )

        # Create isolated temporary directory strictly OUTSIDE workspace for evidence collection
        report_dir = tempfile.mkdtemp(prefix=".agent_verification_evidence_")
        report_filename = f"junit_{uuid.uuid4().hex}.xml"
        report_host_path = os.path.join(report_dir, report_filename)
        # Pre-create empty report file with restricted permissions (0o600)
        with open(report_host_path, "w", encoding="utf-8") as f:
            pass
        if hasattr(os, "chmod"):
            try:
                os.chmod(report_host_path, 0o600)
                os.chmod(report_dir, 0o700)
            except Exception:
                pass

        register_authorized_evidence_dir(report_host_path)
        register_authorized_evidence_dir(report_dir)

        sandbox_mode = kwargs.get("sandbox_mode", "container")
        exec_cmd = command
        cmd_kwargs = {k: v for k, v in kwargs.items() if k not in ("call_id", "command", "check_name", "check_type")}

        is_pytest = "pytest" in command.lower()
        if is_pytest:
            # Force verbose mode so pytest outputs every single executed testcase identity to stdout
            has_verbose = any(v in command.split() for v in ("-v", "-vv", "--verbose"))
            verbose_arg = "" if has_verbose else " -v"
            if sandbox_mode == "container":
                # Mount ONLY the single pre-created report file directly to /verification_evidence/report_filename:rw
                extra_mounts = list(cmd_kwargs.get("extra_mounts", []))
                extra_mounts.append(f"{report_host_path}:/verification_evidence/{report_filename}:rw")
                cmd_kwargs["extra_mounts"] = extra_mounts
                exec_cmd = f"{command}{verbose_arg} --junitxml=/verification_evidence/{report_filename}"
            else:
                allowed_paths = list(cmd_kwargs.get("allowed_paths", []))
                allowed_paths.append(report_host_path)
                allowed_paths.append(report_dir)
                cmd_kwargs["allowed_paths"] = allowed_paths
                exec_cmd = f'{command}{verbose_arg} --junitxml="{report_host_path}"'

        try:
            res = await self._command_tool.execute(
                workspace_path=workspace_path,
                call_id=call_id,
                command=exec_cmd,
                timeout_seconds=90,
                **cmd_kwargs,
            )

            exit_code = res.artifacts.get("exit_code") if res.artifacts else None
            is_success = (exit_code == 0)

            # Extract structured execution record with dual-channel cross-validation
            trusted_record: Optional[TrustedExecutionRecord] = None
            parsed: Optional[Dict[str, Any]] = None
            cross_check_passed = False
            tampering_detected = False
            discrepancy_msg = ""

            if report_host_path and os.path.exists(report_host_path) and not os.path.islink(report_host_path):
                # Check report file creation timestamp is strictly at or after t0
                report_stat = os.stat(report_host_path)
                if report_stat.st_mtime >= (t0 - 1.0) and report_stat.st_size > 0:
                    parsed = parse_junit_xml_report(report_host_path)
                    if parsed and is_success and parsed["total"] > 0 and parsed["passed"] > 0:
                        # Authenticate execution result against runner's console stdout (counts AND node identities)
                        if is_pytest:
                            console_summary = extract_pytest_console_summary(res.output)
                            console_nodes = extract_pytest_console_passed_nodes(res.output)

                            if not console_summary:
                                tampering_detected = True
                                discrepancy_msg = "Discrepancy: Runner console output did not contain an authentic pytest execution summary line."
                            elif (
                                parsed["passed"] != console_summary["passed"]
                                or parsed["failed"] != console_summary["failed"]
                                or parsed["skipped"] != console_summary["skipped"]
                                or parsed["total"] != console_summary["total"]
                            ):
                                tampering_detected = True
                                discrepancy_msg = (
                                    f"Tampering detected: Report counts ({parsed['passed']} passed, {parsed['failed']} failed) "
                                    f"do not match runner console summary ({console_summary['passed']} passed, {console_summary['failed']} failed)."
                                )
                            elif not console_nodes:
                                # Mandatory identity evidence: verbose runner output must contain individual testcase identities
                                tampering_detected = True
                                discrepancy_msg = "Discrepancy: Runner console output did not contain individual testcase execution confirmations (verbose runner output required)."
                            else:
                                # Strict one-for-one testcase validation: every testcase in XML report must have matching console confirmation
                                unconfirmed_cases = []
                                ast_cache: Dict[str, Set[str]] = {}

                                for tc in parsed.get("passed_testcases", []):
                                    tc_name = tc.get("name", "").strip().lower()
                                    tc_file = tc.get("file", "").strip().replace("\\", "/").lower()
                                    tc_class = tc.get("classname", "").strip().lower()
                                    if not tc_file and tc_class:
                                        tc_file = "/".join(tc_class.split(".")) + ".py"

                                    clean_rel = os.path.normpath(tc_file).replace("\\", "/").lower() if tc_file else ""
                                    canonical = f"{clean_rel}::{tc_name}" if clean_rel else ""

                                    class_name_part = tc_class.split(".")[-1].lower() if tc_class else ""
                                    class_canonical = f"{clean_rel}::{class_name_part}::{tc_name}" if (clean_rel and class_name_part) else ""

                                    # Exact normalized identity matching against runner console node confirmations
                                    matched = False
                                    if canonical and canonical in console_nodes:
                                        matched = True
                                    elif class_canonical and class_canonical in console_nodes:
                                        matched = True

                                    if not matched:
                                        unconfirmed_cases.append(canonical or f"{tc_class}::{tc_name}")
                                        continue

                                    # Fail-closed AST and workspace containment validation
                                    if not clean_rel or ".." in clean_rel.split("/"):
                                        tampering_detected = True
                                        discrepancy_msg = f"Tampering detected: Testcase '{tc_name}' specifies invalid or escaping file path '{tc_file}'."
                                        break

                                    real_ws = os.path.realpath(workspace_path)
                                    candidate_host_path = os.path.normpath(os.path.join(workspace_path, clean_rel))
                                    real_host = os.path.realpath(candidate_host_path)

                                    try:
                                        is_contained = (os.path.commonpath([real_ws, real_host]) == real_ws)
                                    except ValueError:
                                        is_contained = False

                                    if not is_contained:
                                        tampering_detected = True
                                        discrepancy_msg = f"Tampering detected: Test source file '{tc_file}' escapes workspace boundary."
                                        break

                                    if not os.path.isfile(real_host) or os.path.islink(real_host):
                                        tampering_detected = True
                                        discrepancy_msg = f"Tampering detected: Test source file '{tc_file}' does not exist on host filesystem or is an untrusted symlink."
                                        break

                                    if real_host.endswith(".py"):
                                        if real_host not in ast_cache:
                                            funcs: Set[str] = set()
                                            try:
                                                with open(real_host, "r", encoding="utf-8", errors="replace") as sf:
                                                    tree = ast.parse(sf.read(), filename=real_host)
                                                for node in ast.walk(tree):
                                                    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                                                        funcs.add(node.name.lower())
                                            except Exception as parse_exc:
                                                tampering_detected = True
                                                discrepancy_msg = f"Tampering detected: Test source file '{tc_file}' failed AST parsing ({parse_exc})."
                                                break

                                            if not funcs:
                                                tampering_detected = True
                                                discrepancy_msg = f"Tampering detected: Test source file '{tc_file}' contains zero AST-defined test functions."
                                                break

                                            ast_cache[real_host] = funcs

                                        base_test_fn = tc_name.split("[")[0].strip().lower()
                                        if base_test_fn not in ast_cache[real_host]:
                                            tampering_detected = True
                                            discrepancy_msg = f"Tampering detected: Testcase '{tc_name}' is not defined in source file '{tc_file}' AST."
                                            break

                                if unconfirmed_cases and not tampering_detected:
                                    tampering_detected = True
                                    discrepancy_msg = f"Tampering detected: Report contains unconfirmed testcase identities: {unconfirmed_cases[:5]}"
                                elif not unconfirmed_cases and not tampering_detected:
                                    cross_check_passed = True
                        else:
                            if check_type in ("test", VerificationCheckType.TEST):
                                runner_name = command.split()[0] if command else "unknown"
                                discrepancy_msg = (
                                    f"Runner limitation: Command '{runner_name}' is not supported for structured cryptographic verification. "
                                    "Structured JUnit XML records and dual-channel validation currently require 'pytest'."
                                )

                        if cross_check_passed and not tampering_detected:
                            try:
                                trusted_record = issue_trusted_execution_record(
                                    run_id=kwargs.get("task_id") or kwargs.get("run_id") or call_id,
                                    runner="pytest",
                                    command=command,
                                    exit_code=exit_code if exit_code is not None else -1,
                                    total=parsed["total"],
                                    passed=parsed["passed"],
                                    failed=parsed["failed"],
                                    skipped=parsed.get("skipped", 0),
                                    passed_nodes=parsed["passed_nodes"],
                                    failed_nodes=parsed["failed_nodes"],
                                    skipped_nodes=parsed.get("skipped_nodes", []),
                                )
                            except ValueError:
                                trusted_record = None

            evidence = (
                f"Verification Check '{check_name}' ({check_type}) exited with code {exit_code}. "
                f"{'PASSED' if is_success else 'FAILED'}."
            )
            if parsed:
                evidence += f" [{parsed['passed']} passed, {parsed['failed']} failed, {parsed['skipped']} skipped of {parsed['total']} tests]"

            # Fail-closed: for test checks, verification requires verified trusted execution record and zero tampering
            if check_type == "test":
                verification_passed = is_success and cross_check_passed and (trusted_record is not None) and not tampering_detected
                error_msg = res.error or (discrepancy_msg if discrepancy_msg else ("Verification failed: No verified trusted execution record produced." if not verification_passed else None))
            else:
                verification_passed = is_success and not tampering_detected
                error_msg = res.error or (discrepancy_msg if discrepancy_msg else None)

            return ActionResult(
                call_id=call_id,
                tool_name=self.name,
                success=verification_passed,
                output=res.output,
                error=error_msg,
                artifacts={
                    "check_name": check_name,
                    "check_type": check_type,
                    "command": command,
                    "exit_code": exit_code,
                    "evidence_summary": evidence + (f" [{discrepancy_msg}]" if discrepancy_msg else ""),
                    "passed": verification_passed,
                    "cross_check_passed": cross_check_passed,
                    "tampering_detected": tampering_detected,
                    "discrepancy": discrepancy_msg if discrepancy_msg else None,
                    "trusted_execution_record": trusted_record.model_dump() if trusted_record else None,
                },
                execution_time_ms=(time.time() - t0) * 1000,
            )
        finally:
            if report_host_path:
                unregister_authorized_evidence_dir(report_host_path)
            if report_dir:
                unregister_authorized_evidence_dir(report_dir)
                if os.path.exists(report_dir):
                    shutil.rmtree(report_dir, ignore_errors=True)
